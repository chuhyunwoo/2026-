        {"q": "2. 새로운 사람들을 만나는 자리에서 나는?", "A": ("먼저 말을 걸고 분위기를 주도한다.", "E"), "B": ("주로 다른 사람이 말을 걸어주기를 기다린다.", "I")},
        {"q": "3. 생각을 정리할 때 나는?", "A": ("말하면서 생각하는 편이다.", "E"), "B": ("속으로 깊게 생각한 뒤 말한다.", "I")},
        
        # S vs N
        {"q": "4. 영화를 볼 때 더 집중하는 것은?", "A": ("현실적인 스토리와 디테일한 연출", "S"), "B": ("상상력을 자극하는 세계관과 상징", "N")},
